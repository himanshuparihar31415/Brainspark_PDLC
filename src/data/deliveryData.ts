/**
 * The delivery seed set: what has been specified for Mobile Banking V2, and what
 * is actually being done about it.
 *
 * Ten stories, hand-written. The previous thirty were generated to a
 * distribution, which meant every acceptance criterion read "when {the title} is
 * exercised, then the behaviour holds and is recorded in the audit log" — the
 * same sentence thirty times, describing nothing. Ten stories whose criteria are
 * actually testable demonstrate the product; thirty that share one template
 * demonstrate a loop.
 *
 * The relationships are deliberately imperfect, because the measures the delivery
 * view exists to surface are the negative ones:
 *
 *   · three stories carry no delivery task    → storiesWithoutTasks
 *   · three story-work tasks carry no story   → tasksWithoutStories (scope creep)
 *   · two stories were invalidated upstream   → staleStories
 *   · two stories were never exported         → neverExported
 *   · one story and one task are blocked      → attention
 *
 * A seed set without those conditions would leave the most useful widgets
 * permanently empty and untested.
 *
 * Feature names join to `GENERATED_MODULES` by string, so they must match it
 * exactly. `st-9` deliberately does not: it says "Device registration" where the
 * module map now says "Register device", which is what a feature rename does to
 * the stories underneath it. That story lands in the Detached bucket, which is
 * the only way that bucket gets exercised.
 *
 * The five non-story tasks — operations, spike, governance, bug — have no
 * specification by nature and must never be counted as gaps. A measure that
 * flags an incident for having no user story is noise, and noise trains people
 * to ignore the real signal.
 */

