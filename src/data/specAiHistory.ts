/** Get unique session IDs sorted by most recent activity */
export function getSessionIds(entries: SpecHistoryEntry[]): string[] {
  const sessionLatest = new Map<string, string>();
  for (const e of entries) {
    const existing = sessionLatest.get(e.sessionId);
    if (!existing || e.timestamp > existing) {
      sessionLatest.set(e.sessionId, e.timestamp);
    }
  }
  return [...sessionLatest.entries()]
    .sort((a, b) => b[1].localeCompare(a[1]))
    .map(([id]) => id);
}

/** Get unique artifact names from history */
export function getArtifactNames(entries: SpecHistoryEntry[]): string[] {
  const names = new Set<string>();
  for (const e of entries) {
    if (e.artifactName) names.add(e.artifactName);
  }
  return [...names].sort();
}
